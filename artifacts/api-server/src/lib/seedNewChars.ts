export async function seedNewChars(): Promise<void> {
  // Remove legacy universes that are no longer part of the roster
  const removedUniverses = ["Animals", "Animal Kingdom"];
  const deleted = await db
    .delete(charactersTable)
    .where(inArray(charactersTable.universe, removedUniverses));
  if ((deleted.rowCount ?? 0) > 0) {
    console.log(`[seed] Removed ${deleted.rowCount} legacy character(s) from deprecated universes`);
  }

  let inserted = 0;
  for (const c of newChars) {
    const existing = await db
      .select({ id: charactersTable.id })
      .from(charactersTable)
      .where(eq(charactersTable.name, c.name))
      .limit(1);
    if (existing.length > 0) continue;
    await db.insert(charactersTable).values(c);
    inserted++;
  }
  if (inserted > 0) {
    console.log(`[seed] Inserted ${inserted} new character(s)`);
  }
}
